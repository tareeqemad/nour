{{-- خطوات العمل للمشغل --}}
<div class="d-section" id="work-steps">
    <div class="d-section-title">
        <i class="bi bi-list-check"></i>
        دليل خطوات العمل الشامل للمشغل
    </div>

    <div class="d-callout d-callout-primary mb-3">
        <div class="d-callout-title"><i class="bi bi-lightbulb"></i> ابدأ من هنا</div>
        <p>اتبع هذه الخطوات بالترتيب لإعداد حسابك بشكل صحيح. كل خطوة مهمة وتؤثر على الخطوات التالية.</p>
    </div>

    <ol class="d-steps">
        <li class="d-step">
            <h6>إعداد ملف المشغل (إلزامي)</h6>
            <p>هذه الخطوة <strong>إلزامية</strong> ويجب إكمالها قبل أي خطوة أخرى. بدون إكمال ملف المشغل، لن تتمكن من إضافة وحدات التوليد.</p>
            <ul>
                <li>اذهب إلى <strong>المشغل &rarr; ملف المشغل</strong></li>
                <li>أكمل: الاسم بالعربي، اسم المالك، المحافظة، المدينة، العنوان، معلومات الاتصال</li>
                <li>احفظ وتأكد من ظهور رسالة النجاح</li>
            </ul>
        </li>

        <li class="d-step">
            <h6>إضافة وحدات التوليد</h6>
            <p>كل وحدة توليد تمثل موقعاً جغرافياً يحتوي على مولدات.</p>
            <ul>
                <li>وحدات التوليد &rarr; إضافة وحدة جديدة &rarr; الاسم، المحافظة، المدينة، العنوان</li>
                <li><strong>تحديد الموقع الجغرافي:</strong> تبويب الموقع &rarr; انقر على الخريطة &rarr; اسم المنطقة + المساحة (0.1 - 360 كم&#178;)</li>
                <li>النظام يمنع التداخل مع مناطق مشغلين آخرين</li>
            </ul>
        </li>

        <li class="d-step">
            <h6>إضافة المولدات</h6>
            <p>يمكنك إضافة عدة مولدات لكل وحدة توليد.</p>
            <ul>
                <li>المولدات &rarr; إضافة مولد جديد &rarr; اختر وحدة التوليد</li>
                <li>أدخل: الرقم (أو توليد تلقائي)، النوع، القدرة، الشركة المصنعة، الرقم التسلسلي، تاريخ الشراء</li>
            </ul>
        </li>

        <li class="d-step">
            <h6>إضافة فريق العمل</h6>
            <p>أضف فني مشغل أو محاسب لمساعدتك في إدارة العمليات.</p>
            <ul>
                <li>فريق العمل &rarr; إضافة مستخدم &rarr; الاسم (عربي + إنجليزي) + الجوال + الدور</li>
                <li>يتم توليد username + password + SMS تلقائياً</li>
                <li>خصص الصلاحيات من صفحة <strong>الصلاحيات</strong></li>
            </ul>
        </li>

        <li class="d-step">
            <h6>تسجيل السجلات اليومية</h6>
            <p>سجلات مهمة لتتبع الأداء والامتثال:</p>
            <ul>
                <li><strong>سجلات التشغيل:</strong> التاريخ، وقت البدء/الانتهاء، الطاقة المنتجة، الوقود المستهلك</li>
                <li><strong>سجلات الصيانة:</strong> النوع (دورية/طارئة/وقائية)، التفاصيل، التكلفة</li>
                <li><strong>الامتثال والسلامة:</strong> التقارير والفحوصات</li>
                <li><strong>كفاءة الوقود:</strong> بيانات الاستهلاك والكفاءة</li>
            </ul>
        </li>

        <li class="d-step">
            <h6>إدارة أسعار التعرفة</h6>
            <p>حدد أسعار التعرفة الكهربائية لكل وحدة توليد.</p>
            <ul>
                <li>المشغل &rarr; أسعار التعرفة &rarr; اختر الوحدة &rarr; أضف سعر جديد مع تاريخ البدء/الانتهاء</li>
            </ul>
        </li>

        <li class="d-step">
            <h6>المراقبة والتحليل</h6>
            <p>استخدم لوحة التحكم والتقارير لمراقبة أداء مولداتك واتخاذ قرارات مدروسة. راقب الإحصائيات الشاملة، كفاءة الوقود، والسجلات التاريخية.</p>
        </li>
    </ol>
</div>
